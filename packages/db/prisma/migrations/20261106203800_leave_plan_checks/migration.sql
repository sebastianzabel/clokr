-- Issue #835 (Phase 835, D-835-01/02/08, AC-1/AC-12): database backstops of the leave plan (Urlaubsplaner).
-- Prisma models no CHECK constraint, no partial unique index and no exclusion constraint, and `prisma migrate diff`
-- ignores them, so this file is hand-written and the CI drift guard stays empty (precedent:
-- `*_leave_limit_rule_checks`, TimeEntry_no_overlap_closed, TimeEntry_employeeId_date_open_unique). The application
-- rules live in the leave-plan module and its routes; these statements only make a malformed or racing write
-- impossible for every writer. Both tables are new (migration `*_leave_plan`), so no existing row can violate them.
--
-- Why a separate, later file than the tables: the tables and the enum are generated by `migrate diff` in the
-- previous migration; hand-written statements never share a file with generated ones, so a regeneration can never
-- swallow or duplicate them. One concern per statement.
--
-- Valid on PostgreSQL 17 (prod) and 18 (int, CI). btree_gist is already installed by the
-- `*_time_entry_no_overlap` migration; the IF NOT EXISTS below only makes this file self-contained.

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- At most one OPEN plan per salon and year. A TAKEN_OVER plan does not count, so a new plan can be opened after a
-- takeover (D-835-01).
CREATE UNIQUE INDEX "LeavePlan_open_unique" ON "LeavePlan"("salonId", "year") WHERE "status" = 'OPEN';

-- The plan year is a plausible calendar year.
ALTER TABLE "LeavePlan" ADD CONSTRAINT "LeavePlan_year_check" CHECK ("year" BETWEEN 2000 AND 2100);

-- A TAKEN_OVER plan names when and by whom; an OPEN plan names neither.
ALTER TABLE "LeavePlan" ADD CONSTRAINT "LeavePlan_taken_over_shape_check" CHECK (
  ("status" = 'OPEN'       AND "takenOverAt" IS NULL     AND "takenOverByUserId" IS NULL) OR
  ("status" = 'TAKEN_OVER' AND "takenOverAt" IS NOT NULL AND "takenOverByUserId" IS NOT NULL)
);

-- A wish is not inverted.
ALTER TABLE "LeavePlanWish" ADD CONSTRAINT "LeavePlanWish_range_check" CHECK ("startDate" <= "endDate");

-- A half day is a single day.
ALTER TABLE "LeavePlanWish" ADD CONSTRAINT "LeavePlanWish_half_day_check"
  CHECK (NOT "halfDay" OR "startDate" = "endDate");

-- A refusal code, its message and its time are stored together or not at all.
ALTER TABLE "LeavePlanWish" ADD CONSTRAINT "LeavePlanWish_refusal_shape_check" CHECK (
  ("refusalCode" IS NULL     AND "refusalMessage" IS NULL     AND "refusedAt" IS NULL) OR
  ("refusalCode" IS NOT NULL AND "refusalMessage" IS NOT NULL AND "refusedAt" IS NOT NULL)
);

-- A wish is linked to its request exactly when it carries the takeover time.
ALTER TABLE "LeavePlanWish" ADD CONSTRAINT "LeavePlanWish_link_shape_check"
  CHECK (("leaveRequestId" IS NULL) = ("takenOverAt" IS NULL));

-- A removed wish names who removed it; a live wish names nobody.
ALTER TABLE "LeavePlanWish" ADD CONSTRAINT "LeavePlanWish_removal_shape_check"
  CHECK (("deletedAt" IS NULL) = ("deletedByUserId" IS NULL));

-- Defence in depth for the application overlap check (A-10): two active (not removed), not yet taken-over wishes of
-- one person never overlap, inclusive on both ends (daterange '[]'). A removed or linked wish is outside the
-- constraint, as is a wish of another person.
ALTER TABLE "LeavePlanWish" ADD CONSTRAINT "LeavePlanWish_no_overlap_active"
  EXCLUDE USING gist ("employeeId" WITH =, daterange("startDate", "endDate", '[]') WITH &&)
  WHERE ("deletedAt" IS NULL AND "leaveRequestId" IS NULL);
